import os
import re
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
FRAMES_DIR = PROJECT_ROOT / "public" / "frames" / "PNG Sequence"
MANIFEST_PATH = PROJECT_ROOT / "lib" / "frames-manifest.ts"

old_frames = []
new_frames = []
third_frames = []

for f in os.listdir(FRAMES_DIR):
    m = re.match(r"^frame_(\d+)\.webp$", f)
    if m:
        old_frames.append(int(m.group(1)))
        continue
    m = re.match(r"^Shega Website Video (\d+)\.webp$", f)
    if m:
        new_frames.append(int(m.group(1)))
        continue
    m = re.match(r"^(\d{4})\.webp$", f)
    if m:
        third_frames.append(int(m.group(1)))

old_frames.sort()
new_frames.sort()
third_frames.sort()

content = f"""// Auto-generated by scripts/generate-frames-manifest.py — do not edit by hand.
export const OLD_SEQUENCE_FRAMES: readonly number[] = {old_frames};
export const NEW_SEQUENCE_FRAMES: readonly number[] = {new_frames};
export const THIRD_SEQUENCE_FRAMES: readonly number[] = {third_frames};
"""

with open(MANIFEST_PATH, "w", encoding="utf-8") as fh:
    fh.write(content)

print(f"Wrote {len(old_frames)} old frames, {len(new_frames)} new frames, {len(third_frames)} third frames to {MANIFEST_PATH}")
